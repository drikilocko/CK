create table if not exists public.ck_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.ck_sessions (
  token_hash text primary key,
  user_id bigint not null references public.ck_users(id) on delete cascade,
  expires_at bigint not null
);

create table if not exists public.ck_orders (
  id bigint generated by default as identity primary key,
  reference text unique,
  user_id bigint not null references public.ck_users(id),
  customer_name text not null,
  phone text not null,
  destination text not null check (destination in ('benin', 'togo')),
  location text not null,
  notes text not null default '',
  items_json jsonb not null,
  subtotal_eur double precision not null,
  shipping_fcfa bigint not null,
  total_fcfa bigint not null,
  status text not null default 'demande_recue'
    check (status in (
      'demande_recue', 'devis_envoye', 'colis_en_commande',
      'commande_fournisseur', 'dans_avion', 'arrive', 'livre'
    )),
  quote_total_fcfa bigint,
  quote_sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_ck_sessions_expiry on public.ck_sessions(expires_at);
create index if not exists idx_ck_orders_user_id on public.ck_orders(user_id);

create or replace function public.set_order_reference()
returns trigger
language plpgsql
as $$
begin
  if new.reference is null or new.reference = '' then
    new.reference := 'REL-' || lpad(new.id::text, 6, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists ck_orders_set_reference on public.ck_orders;
create trigger ck_orders_set_reference
before insert on public.ck_orders
for each row execute function public.set_order_reference();

